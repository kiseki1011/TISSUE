    ADD CONSTRAINT member_agent_type_check
    CHECK (agent_type IS NULL OR (agent_type)::text = ANY ((ARRAY[
        'DEVELOPMENT', 'PLANNING', 'MANAGEMENT', 'DESIGN', 'QA', 'GENERAL']::character varying[])::text[]));

ALTER TABLE public.member
    ADD CONSTRAINT fk_member_model FOREIGN KEY (model_id) REFERENCES public.ai_model(id);

CREATE INDEX idx_member_model_id ON public.member (model_id);
